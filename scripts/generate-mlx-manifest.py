#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["packaging>=24"]
# ///
"""Regenerate packages/core/src/embedding/mlx-manifest.ts.

Pins the local MLX runtime: a standalone CPython, every wheel in the full
mlx-vlm dependency closure for native arm64 macOS 14+, and every file of the
pinned model revision, each with its SHA-256. Run from the repository root:

    uv run scripts/generate-mlx-manifest.py

uv resolves the closure once here, on the maintainer's machine; installation
on the user's machine downloads exactly these files and installs them with
pip --no-index --no-deps, so no resolver runs there.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

from packaging.tags import compatible_tags, cpython_tags, mac_platforms
from packaging.utils import canonicalize_name, parse_wheel_filename

MLX_VLM = "mlx-vlm==0.7.9"
MODEL = "mlx-community/embeddinggemma-2-8bit"
REVISION = "7505ef2f8ddef45efef6d060865f27989b3c9cec"
PYTHON = {
    "path": "python.tar.gz",
    "url": "https://github.com/astral-sh/python-build-standalone/releases/download/20260211/cpython-3.12.12%2B20260211-aarch64-apple-darwin-install_only_stripped.tar.gz",
    "sha256": "22625deaf5757e7c266cf1a096c9151a06b598b1e14632a2ec9993d58ec5fe84",
}
# Model files that inference never reads.
SKIP_MODEL_FILES = {".gitattributes", "README.md"}
OUT = Path("packages/core/src/embedding/mlx-manifest.ts")


def get_json(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return json.load(response)


def resolve_closure():
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp, "requirements.in")
        source.write_text(MLX_VLM + "\n")
        env = {**os.environ, "MACOSX_DEPLOYMENT_TARGET": "14.0"}
        output = subprocess.run(
            ["uv", "pip", "compile", str(source), "--python-version", "3.12",
             "--python-platform", "aarch64-apple-darwin", "--only-binary", ":all:",
             "--no-header", "--no-annotate", "--quiet"],
            check=True, capture_output=True, text=True, env=env).stdout
    pins = []
    for line in output.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            name, version = line.split("==")
            pins.append((name, version))
    return pins


def pick_wheel(name, version, tag_rank):
    release = get_json(f"https://pypi.org/pypi/{name}/{version}/json")
    best = None
    for file in release["urls"]:
        if file["packagetype"] != "bdist_wheel":
            continue
        _, _, _, tags = parse_wheel_filename(file["filename"])
        rank = min((tag_rank[tag] for tag in tags if tag in tag_rank), default=None)
        if rank is not None and (best is None or rank < best[0]):
            best = (rank, file)
    if best is None:
        sys.exit(f"No macOS 14 arm64 cp312 wheel for {name}=={version}")
    file = best[1]
    return {"path": f"wheels/{file['filename']}", "url": file["url"], "sha256": file["digests"]["sha256"]}


def model_artifacts():
    tree = get_json(f"https://huggingface.co/api/models/{MODEL}/tree/{REVISION}?recursive=true")
    artifacts = []
    for entry in sorted(tree, key=lambda e: e["path"]):
        if entry["type"] != "file" or entry["path"] in SKIP_MODEL_FILES:
            continue
        url = f"https://huggingface.co/{MODEL}/resolve/{REVISION}/{entry['path']}"
        if entry.get("lfs"):
            digest = entry["lfs"]["oid"]
        else:
            with urllib.request.urlopen(url, timeout=60) as response:
                digest = hashlib.sha256(response.read()).hexdigest()
        artifacts.append({"path": f"model/{entry['path']}", "url": url, "sha256": digest})
    return artifacts


def main():
    platforms = list(mac_platforms((14, 0), "arm64"))
    tags = list(cpython_tags((3, 12), platforms=platforms)) + list(compatible_tags((3, 12), "cp312", platforms))
    tag_rank = {tag: index for index, tag in enumerate(tags)}
    pins = resolve_closure()
    wheels = [pick_wheel(name, version, tag_rank) for name, version in pins]
    artifacts = [PYTHON, *wheels, *model_artifacts()]
    versions = {canonicalize_name(name): version for name, version in pins}
    OUT.write_text(
        "// Generated by scripts/generate-mlx-manifest.py; do not edit by hand. See docs/MLX_MODELS.md.\n"
        f'export const MLX_MODEL = "{MODEL}";\n'
        f'export const MLX_REVISION = "{REVISION}";\n'
        "/** mlx-vlm release whose EmbeddingGemma 2 model and processor the worker runs. */\n"
        f'export const MLX_VLM_VERSION = "{versions["mlx-vlm"]}";\n'
        "export const MLX_DIMENSION = 768;\n"
        f"export const MLX_ARTIFACTS = {json.dumps(artifacts, indent=4)} as const;\n")
    print(f"Wrote {OUT}: {len(wheels)} wheels, {len(artifacts) - len(wheels) - 1} model files")


if __name__ == "__main__":
    main()
